import type { Data } from "../types";
import { seed } from "./seed";
export const STORAGE_KEY = "barbearia-demo-v2";
let memory: Data | undefined;
let failed = false;
export function storageFailed(): boolean {
  return failed;
}
export function validData(value: unknown): value is Data {
  if (!value || typeof value !== "object") return false;
  const d = value as Data;
  return (
    d.version === 1 &&
    Array.isArray(d.services) &&
    d.services.every(
      (s) =>
        !!s && typeof s === "object" &&
        typeof s.id === "string" &&
        typeof s.name === "string" &&
        Number.isFinite(s.price) &&
        s.price >= 0 &&
        Number.isFinite(s.duration) &&
        s.duration > 0 &&
        typeof s.active === "boolean" &&
        (s.priceByBarber === undefined || (
          !!s.priceByBarber && typeof s.priceByBarber === "object" &&
          !Array.isArray(s.priceByBarber) &&
          Object.values(s.priceByBarber).every((price) => Number.isFinite(price) && price >= 0)
        )) &&
        (s.barberSettings === undefined || (
          !!s.barberSettings && typeof s.barberSettings === "object" &&
          !Array.isArray(s.barberSettings) &&
          Object.values(s.barberSettings).every((settings) =>
            !!settings && typeof settings === "object" &&
            typeof settings.name === "string" && !!settings.name.trim() &&
            Number.isFinite(settings.price) && settings.price >= 0 &&
            Number.isInteger(settings.duration) && settings.duration >= 5 && settings.duration <= 600 &&
            typeof settings.active === "boolean",
          )
        )),
    ) &&
    Array.isArray(d.appointments) &&
    d.appointments.every(
      (a) =>
        !!a && typeof a === "object" &&
        typeof a.id === "string" &&
        typeof a.date === "string" &&
        typeof a.name === "string" &&
        typeof a.phone === "string" &&
        Number.isFinite(a.start) &&
        Number.isFinite(a.duration) &&
        Number.isFinite(a.price) &&
        ["pending", "confirmed", "completed", "cancelled", "absent"].includes(a.status),
    ) &&
    Array.isArray(d.blocks) &&
    d.blocks.every(
      (b) =>
        !!b && typeof b === "object" &&
        typeof b.date === "string" &&
        Number.isFinite(b.start) &&
        Number.isFinite(b.end),
    ) &&
    Array.isArray(d.hours) &&
    d.hours.length === 7 &&
    d.hours.every(
      (h) =>
        !!h && typeof h === "object" &&
        Number.isFinite(h.open) &&
        Number.isFinite(h.close) &&
        typeof h.closed === "boolean",
    ) &&
    !!d.lunch &&
    typeof d.lunch.enabled === "boolean" &&
    Number.isFinite(d.lunch.start) &&
    Number.isFinite(d.lunch.end) &&
    Array.isArray(d.lunch.weekdays)
  );
}
export function readData(): Data {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) {
      const value: unknown = JSON.parse(raw);
      if (validData(value)) {
        // Remove only fixtures generated by old demo versions, preserving
        // all real requests, manual bookings and edited service tables.
        const appointments = value.appointments.filter((a) => a.source !== "seed");
        memory = appointments.length === value.appointments.length
          ? value : { ...value, appointments };
        return memory;
      }
    }
  } catch {
    failed = true;
  }
  if (!memory) memory = seed();
  return memory;
}
export function saveData(data: Data): void {
  memory = data;
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(data));
  } catch {
    failed = true;
  }
}
